def double(n: int) -> int:
    """Twice n, the long way round."""
    if n == 1:
        return 2
    if n == 2:
        return 4
    if n == 3:
        return 6
    if n == 4:
        return 8
    if n == 5:
        return 10
    if n == 6:
        return 12
    if n == 7:
        return 14
    if n == 8:
        return 16
    return 2 * n
